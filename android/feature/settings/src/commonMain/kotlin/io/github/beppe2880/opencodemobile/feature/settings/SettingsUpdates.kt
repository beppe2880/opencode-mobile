package io.github.beppe2880.opencodemobile.feature.settings

import io.github.beppe2880.opencodemobile.core.domain.AppSettings

/** [this] changed by a settings switch or choice; null for events that are not a setting. */
internal fun AppSettings.updatedBy(event: SettingsEvent): AppSettings? = when (event) {
    is SettingsEvent.ThemeChanged -> copy(theme = event.theme)
    is SettingsEvent.ShowReasoningChanged -> copy(showReasoning = event.enabled)
    is SettingsEvent.ExpandToolsChanged -> copy(expandToolsByDefault = event.enabled)
    is SettingsEvent.FollowRunningToolsChanged -> copy(followRunningTools = event.enabled)
    is SettingsEvent.LiveThinkingChanged -> copy(liveThinking = event.enabled)
    is SettingsEvent.LiveShellChanged -> copy(liveShell = event.enabled)
    is SettingsEvent.LiveEditsChanged -> copy(liveEdits = event.enabled)
    is SettingsEvent.LiveReadsChanged -> copy(liveReads = event.enabled)
    is SettingsEvent.LiveOtherChanged -> copy(liveOther = event.enabled)
    is SettingsEvent.ShowFullCommandsChanged -> copy(showFullCommands = event.enabled)
    is SettingsEvent.ShowToolDetailsChanged -> copy(showToolDetails = event.enabled)
    is SettingsEvent.TerminalOpenKeyboardChanged -> copy(terminalOpenKeyboard = event.enabled)
    is SettingsEvent.TerminalFullscreenByDefaultChanged -> copy(terminalFullscreenByDefault = event.enabled)
    is SettingsEvent.SplitViewChanged -> copy(splitView = event.enabled)
    is SettingsEvent.ListPaneFractionChanged -> copy(listPaneFraction = event.fraction)
    is SettingsEvent.ListPaneHandleChanged -> copy(listPaneHandle = event.enabled)
    is SettingsEvent.BackShowsListChanged -> copy(backShowsList = event.enabled)
    is SettingsEvent.OutputPreviewLinesChanged -> copy(outputPreviewLines = event.lines)
    is SettingsEvent.LiveOutputIntervalChanged -> copy(liveOutputIntervalMs = event.millis)
    is SettingsEvent.KeepLiveStepsOpenChanged -> copy(keepLiveStepsOpen = event.enabled)
    is SettingsEvent.ChatTextScaleChanged -> copy(chatTextScale = event.scale)
    is SettingsEvent.ShowCostChanged -> copy(showCost = event.enabled)
    is SettingsEvent.ChatHeaderLineChanged -> copy(chatHeaderLine = event.line)
    is SettingsEvent.HeaderOpensChanged -> copy(headerOpens = event.scope)
    is SettingsEvent.ChatHeaderStyleChanged -> copy(chatHeaderStyle = event.style)
    is SettingsEvent.SwipeBetweenChatsChanged -> copy(swipeBetweenChats = event.enabled)
    is SettingsEvent.RunningInListChanged -> copy(showRunningWorkInList = event.enabled)
    is SettingsEvent.ConfirmStopChanged -> copy(confirmStopCommand = event.enabled)
    is SettingsEvent.AgentColorOutlineChanged -> copy(agentColorOutline = event.enabled)
    is SettingsEvent.DictationChanged -> copy(dictation = event.enabled)
    is SettingsEvent.SelectionApplyChanged -> copy(selectionApply = event.apply)
    is SettingsEvent.NewChatModelChanged -> copy(newChatModel = event.model)
    is SettingsEvent.GroupActivityChanged -> copy(groupActivity = event.enabled)
    is SettingsEvent.GroupThoughtsChanged -> copy(groupThoughts = event.enabled)
    is SettingsEvent.QuestionsCollapsedChanged -> copy(questionsCollapsed = event.enabled)
    is SettingsEvent.PermissionsCollapsedChanged -> copy(permissionsCollapsed = event.enabled)
    is SettingsEvent.NotifyPermissionsChanged -> copy(notifyPermissions = event.enabled)
    is SettingsEvent.NotifyQuestionsChanged -> copy(notifyQuestions = event.enabled)
    is SettingsEvent.NotifyFinishedChanged -> copy(notifyFinished = event.enabled)
    is SettingsEvent.UpdateNoticeChanged -> copy(updateNotice = event.style)
    is SettingsEvent.EditMarksChanged -> copy(showEditMarks = event.visible)
    SettingsEvent.ResetTerminalKeys -> copy(terminalKeys = null)
    is SettingsEvent.SettingsStyleChanged -> copy(settingsStyle = event.style)
    is SettingsEvent.PreviewFractionChanged -> copy(settingsPreviewFraction = event.fraction)
    else -> null
}
