/** Small swatch for the settings picker. */
@Immutable
data class OpenCodeThemePreview(
    val background: Color,
    val surface: Color,
    val text: Color,
    val primary: Color,
    val strong: Color,
    val code: Color,
)

/**
 * A theme of the OpenCode terminal app. [displayName] is the name its `/theme` list shows. A theme
 * with a single mode has the same tokens in [light] and [dark], like the TUI uses it for both.
 */
@Immutable
data class OpenCodeTheme(
    val id: String,
    val displayName: String,
    val light: OpenCodeThemeTokens,
    val dark: OpenCodeThemeTokens,
) {
    fun tokens(dark: Boolean): OpenCodeThemeTokens = if (dark) this.dark else light

    /** Small swatch for the settings picker. */
    fun preview(dark: Boolean): OpenCodeThemePreview = tokens(dark).let {
        OpenCodeThemePreview(
            background = it.background,
            surface = it.raised,
            text = it.text,
            primary = it.primary,
            strong = it.markdownStrong,
            code = it.markdownCode,
        )
    }
}

/** The built-in themes of the OpenCode terminal app, generated by `tools/themes`. */
object OpenCodeThemes {
    /** "opencode" (the TUI's default) first, then alphabetical by id. */
    val all: List<OpenCodeTheme> by lazy { generatedOpenCodeThemes() }

    private val index: Map<String, OpenCodeTheme> by lazy { all.associateBy { it.id } }

    /** The theme with [id]; null for null (the app's own colors) and for an unknown id. */
    fun byId(id: String?): OpenCodeTheme? = id?.let { index[it] }
}
