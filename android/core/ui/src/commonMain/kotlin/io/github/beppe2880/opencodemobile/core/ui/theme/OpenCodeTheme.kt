/**
 * One mode of an OpenCode terminal app (TUI) theme, resolved by OpenCode's own `@opencode/theme`
 * (`ResolvedTheme`) and flattened by `tools/themes`. Names follow the resolved tokens:
 *
 * - [background] `background.base`; [raised], [raisedHigh], [raisedMax] `background.raised.*`.
 * - [text], [textMuted], [textFaint] `text.*`; [primary] `hue.interactive[200]`, [accent] `hue.accent[200]`.
 * - [actionPrimaryFocusedBackground] / [actionPrimaryFocusedText]: a selected item on the primary color.
 * - [border] `border.base`, [scrollbar] `scrollbar.base`; [error] ... [info] `text.feedback.*.base`.
 * - [neutral100] ... [neutral900] the neutral hue, 100 the text end and 900 past the background.
 * - [red] ... [purple] step 200 of the chromatic hues, `*Bright` step 100; a theme without the hue
 *   falls back to error, warning (then orange for yellow), success, info, primary and accent.
 * - `diff*`, `syntax*` and `markdown*`: the `diff`, `syntax` and `markdown` tokens.
 * - [isDark]: the text is brighter than the background (OpenCode's own mode detection).
 * - [categorical]: the agent colors, step 200 of each categorical hue without repeats.
 */
