import { describe, expect, test } from "bun:test"
import { DEFAULT_THEME, THEME_IDS, renderKotlin, resolveAll } from "./themes"

const themes = await resolveAll()
const byId = (id: string) => themes.find((theme) => theme.id === id)!

describe("OpenCode themes", () => {
  test("every TUI theme, the default first, ids unique", () => {
    expect(themes.length).toBe(33)
    expect(themes[0]!.id).toBe(DEFAULT_THEME)
    expect(new Set(themes.map((theme) => theme.id)).size).toBe(themes.length)
    expect(themes.map((theme) => theme.id)).toEqual([...THEME_IDS])
    expect(themes.map((theme) => theme.id)).not.toContain("opencode2")
  })

  test("the default dark theme has the TUI markdown colors", () => {
    const dark = byId("opencode").dark
    expect(dark.isDark).toBe(true)
    expect(dark.tokens.markdownStrong).toBe("FFF5A742")
    expect(dark.tokens.markdownCode).toBe("FF7FD88F")
    expect(dark.tokens.markdownLinkText).toBe("FF56B6C2")
    expect(dark.tokens.markdownHeading).toBe("FF9D7CD8")
    expect(dark.tokens.background).toBe("FF0A0A0A")
    expect(dark.tokens.text).toBe("FFEEEEEE")
    expect(dark.tokens.primary).toBe("FFFAB283")
  })

  test("the default light theme is light", () => {
    const light = byId("opencode").light
    expect(light.isDark).toBe(false)
    expect(light.tokens.background).toBe("FFFFFFFF")
    expect(light.tokens.markdownStrong).toBe("FFD68C27")
  })

  test("every mode has every token and agent colors", () => {
    const names = Object.keys(themes[0]!.dark.tokens).sort()
    for (const theme of themes) {
      for (const mode of [theme.light, theme.dark]) {
        expect(Object.keys(mode.tokens).sort()).toEqual(names)
        expect(mode.categorical.length).toBeGreaterThan(0)
        for (const value of Object.values(mode.tokens)) expect(value).toMatch(/^[0-9A-F]{8}$/)
      }
    }
  })

  test("a single-mode theme uses its mode for both", () => {
    for (const theme of themes.filter((theme) => theme.modes.length === 1)) {
      expect(theme.light).toEqual(theme.dark)
    }
  })

  test("the Kotlin file lists every theme", () => {
    const kotlin = renderKotlin(themes)
    expect(kotlin.startsWith("// Generated by tools/themes. Do not edit.")).toBe(true)
    for (const theme of themes) expect(kotlin).toContain(`id = "${theme.id}"`)
    for (const line of kotlin.split("\n")) expect(line.length).toBeLessThanOrEqual(160)
  })
})
